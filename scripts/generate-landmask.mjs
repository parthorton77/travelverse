/**
 * Generates lib/geo/landmask.ts — a run-length-encoded 0.5° land/water grid
 * rasterised from Natural Earth (via the `world-atlas` package).
 *
 * The globe, its 2D fallback and the destination explorer all read this mask,
 * so no Earth textures ever need to be downloaded at runtime.
 *
 * Usage (dependencies are only needed for generation, not for the app):
 *   npm i --no-save world-atlas topojson-client
 *   node scripts/generate-landmask.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import path from "node:path";

const require = createRequire(import.meta.url);
const { feature } = require("topojson-client");
const topology = JSON.parse(readFileSync(require.resolve("world-atlas/land-50m.json"), "utf8"));
const land = feature(topology, topology.objects.land);

const RES = 0.5;
const COLS = 360 / RES;
const ROWS = 180 / RES;

/**
 * Unwrap each ring's longitudes so edges never jump across the antimeridian,
 * and close rings that circle a pole (Antarctica) via the pole itself.
 * Every ring is then a simple closed polygon in an unwrapped lon/lat plane.
 */
const rings = [];
for (const f of land.features ?? [land]) {
  const g = f.geometry;
  const polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
  for (const poly of polys) {
    for (const ring of poly) {
      let offset = 0;
      const out = [[ring[0][0], ring[0][1]]];
      for (let i = 1; i < ring.length; i++) {
        const dx = ring[i][0] - ring[i - 1][0];
        if (dx > 180) offset -= 360;
        else if (dx < -180) offset += 360;
        out.push([ring[i][0] + offset, ring[i][1]]);
      }
      const drift = out[out.length - 1][0] - out[0][0];
      if (Math.abs(drift) > 180) {
        const meanLat = out.reduce((s, p) => s + p[1], 0) / out.length;
        const pole = meanLat < 0 ? -90 : 90;
        out.push([out[out.length - 1][0], pole], [out[0][0], pole], out[0]);
      }
      rings.push(out);
    }
  }
}

// Even-odd fill per ring via XOR, so holes and overlapping unwrapped copies resolve correctly.
const grid = new Uint8Array(COLS * ROWS);
for (let r = 0; r < ROWS; r++) {
  const lat = 90 - (r + 0.5) * RES;
  for (const ring of rings) {
    const xs = [];
    for (let i = 0; i < ring.length - 1; i++) {
      const [x1, y1] = ring[i];
      const [x2, y2] = ring[i + 1];
      if (y1 === y2) continue;
      if (lat >= Math.min(y1, y2) && lat < Math.max(y1, y2)) {
        xs.push(x1 + ((lat - y1) * (x2 - x1)) / (y2 - y1));
      }
    }
    if (xs.length < 2) continue;
    xs.sort((a, b) => a - b);
    for (let k = 0; k + 1 < xs.length; k += 2) {
      const c0 = Math.ceil((xs[k] + 180) / RES - 0.5);
      const c1 = Math.floor((xs[k + 1] + 180) / RES - 0.5);
      for (let c = c0; c <= c1; c++) {
        const wrapped = ((c % COLS) + COLS) % COLS;
        grid[r * COLS + wrapped] ^= 1;
      }
    }
  }
}

// Row-wise RLE: alternating water/land run lengths (base36), rows split by "|".
const rows = [];
for (let r = 0; r < ROWS; r++) {
  const runs = [];
  let current = 0;
  let len = 0;
  for (let c = 0; c < COLS; c++) {
    const v = grid[r * COLS + c];
    if (v === current) len++;
    else {
      runs.push(len);
      current = v;
      len = 1;
    }
  }
  runs.push(len);
  rows.push(runs.map((n) => n.toString(36)).join(","));
}

const out = `// AUTO-GENERATED by scripts/generate-landmask.mjs — do not edit by hand.
// Source: Natural Earth 1:50m land polygons (public domain) via world-atlas.
// Row-wise run-length encoding of a ${COLS}x${ROWS} (${RES}°) land/water grid,
// north → south, west → east. Runs alternate water/land, starting with water.

export const LANDMASK_RESOLUTION = ${RES};
export const LANDMASK_COLS = ${COLS};
export const LANDMASK_ROWS = ${ROWS};
export const LANDMASK_RLE =
  ${JSON.stringify(rows.join("|"))};
`;

const target = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "lib", "geo", "landmask.ts");
writeFileSync(target, out);

// Coarse ASCII preview for sanity checking.
let preview = "";
for (let r = 0; r < ROWS; r += 8) {
  let line = "";
  for (let c = 0; c < COLS; c += 4) line += grid[r * COLS + c] ? "#" : ".";
  preview += line + "\n";
}
console.log(preview);
console.log(`Wrote ${target} (${(out.length / 1024).toFixed(1)} KB)`);
